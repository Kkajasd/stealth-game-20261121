// random.js — tiny seeded RNG (mulberry32) so shot scenes and levels are
// reproducible: the same seed always deals the same patrol jitter and sparkle.
function mulberry32(seed) {
  let a = seed >>> 0;
  return function next() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Pick an integer in [min, max] from a seeded stream.
function randomInt(rand, min, max) {
  return min + Math.floor(rand() * (max - min + 1));
}

// Shuffle a copy of an array with a seeded stream (Fisher-Yates).
function shuffleSeeded(rand, array) {
  const out = array.slice();
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    const tmp = out[i];
    out[i] = out[j];
    out[j] = tmp;
  }
  return out;
}
